import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
import io

uploaded = files.upload()
print("Uploaded files:", list(uploaded.keys()))

filename = list(uploaded.keys())[0]

df = pd.read_csv(io.BytesIO(uploaded[filename]))

print("Data preview:")
print(df.head())

df['Date'] = pd.to_datetime(df['Date'].str.replace(' IST', ''), format='%Y-%m-%d %H:%M:%S %z')
df.sort_values('Date', inplace=True)
df.reset_index(drop=True, inplace=True)

df['Return'] = np.log(df['Close'] / df['Close'].shift(1))
df = df.dropna().reset_index(drop=True)

def compute_I(row):
    if row['High'] != row['Low']:
        return (row['Close'] - row['Open']) / (row['High'] - row['Low'])
    else:
        return 0

df['I'] = df.apply(compute_I, axis=1)

span = 20
df['P_eq'] = df['Close'].ewm(span=span, adjust=False).mean()

k = 0.01
lambda_mr = 0.05
dt = 1
rolling_window = span

predicted_prices = []
prediction_dates = []
actual_prices = []

for i in range(rolling_window, len(df)):
    window = df.iloc[i - rolling_window : i]

    mu_window = window['Return'].ewm(span=rolling_window, adjust=False).mean().iloc[-1]
    sigma_window = window['Return'].ewm(span=rolling_window, adjust=False).std().iloc[-1]

    I_last = window['I'].iloc[-1]

    P_last = window['Close'].iloc[-1]

    P_eq = df['P_eq'].iloc[i - 1]

    mr_term = -lambda_mr * (np.log(P_last) - np.log(P_eq))

    exponent = (mu_window + k * I_last + mr_term - 0.5 * sigma_window**2) * dt
    P_pred = P_last * np.exp(exponent)

    predicted_prices.append(P_pred)
    prediction_dates.append(df['Date'].iloc[i])
    actual_prices.append(df['Close'].iloc[i])

pred_df = pd.DataFrame({
    'Date': prediction_dates,
    'Predicted': predicted_prices,
    'Actual': actual_prices
})

plt.figure(figsize=(12, 6))
plt.plot(pred_df['Date'], pred_df['Actual'], label='Actual Close Price', marker='o')
plt.plot(pred_df['Date'], pred_df['Predicted'], label='Predicted Price', linestyle='--', marker='x')
plt.xlabel('Date')
plt.ylabel('Price')
plt.title('Refined Rolling Forecast: Predicted vs. Actual Prices')
plt.legend()
plt.grid(True)
