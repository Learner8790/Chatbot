fig.update_layout(title='1-Minute Interval Stock Price Prediction',
                  xaxis_title='Time',
                  yaxis_title='Price',
                  hovermode='x unified')
fig.show()

#CSV file

output_filename = 'advanced_minute_prediction_results.csv'
result_df.to_csv(output_filename, index=False)
